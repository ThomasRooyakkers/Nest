"""Builds Nest's own grocery icons into an icon font.

The icons in svg/ are drawn in Lucide's style (24x24 grid, 2px round
strokes, no fill) for groceries Lucide has no glyph for. This script:

1. turns each icon's strokes into filled outlines (picosvg) and merges them
   (skia-pathops), because font glyphs can only be filled shapes;
2. writes nest_flutter/assets/fonts/NestGroceryIcons.ttf with the same
   metrics as Lucide's font (24 units -> 1000 em, ascent 1000, descent 0),
   so both line up in the app;
3. writes the Dart constants in grocery_icons.dart;
4. writes build/preview.html to compare the SVGs, the font and Lucide.

Codepoints are kept in codepoints.json: existing icons keep theirs, new
ones get the next free one. Never reuse or renumber a codepoint.

Run from this folder:
    python3 -m venv .venv && .venv/bin/pip install -r requirements.txt
    .venv/bin/python build.py
Then serve the preview with `node serve_preview.mjs`.
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

import pathops
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path
from picosvg.svg import SVG

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
SVG_DIR = HERE / "svg"
CODEPOINTS = HERE / "codepoints.json"
BUILD = HERE / "build"
FONT_OUT = REPO / "nest_flutter/assets/fonts/NestGroceryIcons.ttf"
DART_OUT = (
    REPO / "nest_flutter/lib/features/shopping_list/presentation/grocery_icons.dart"
)
LUCIDE_TTF = (
    Path.home() / ".pub-cache/hosted/pub.dev/lucide_icons_flutter-4.0.1/assets/lucide.ttf"
)

FAMILY = "NestGroceryIcons"
UPM = 1000
SCALE = UPM / 24
FIRST_CODEPOINT = 0xE000


def load_codepoints(names: list[str]) -> dict[str, int]:
    codepoints = json.loads(CODEPOINTS.read_text()) if CODEPOINTS.exists() else {}
    next_free = max(codepoints.values(), default=FIRST_CODEPOINT - 1) + 1
    for name in names:
        if name not in codepoints:
            codepoints[name] = next_free
            next_free += 1
    CODEPOINTS.write_text(json.dumps(codepoints, indent=2, sort_keys=True) + "\n")
    return codepoints


def outline(svg_file: Path) -> pathops.Path:
    """The icon as one filled outline, in SVG coordinates."""
    pico = SVG.parse(svg_file).topicosvg()
    merged = pathops.Path()
    for shape in pico.shapes():
        path = pathops.Path()
        parse_path(shape.as_path().d, path.getPen())
        merged = pathops.op(merged, path, pathops.PathOp.UNION)
    merged.simplify()
    return merged


def glyph(path: pathops.Path):
    tt_pen = TTGlyphPen(None)
    # SVG y points down, font y points up: flip and scale 24 -> 1000.
    flipped = TransformPen(Cu2QuPen(tt_pen, max_err=1.0, reverse_direction=True),
                           (SCALE, 0, 0, -SCALE, 0, UPM))
    path.draw(flipped)
    return tt_pen.glyph()


def build_font(names: list[str], codepoints: dict[str, int]) -> None:
    order = [".notdef"] + names
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({codepoints[n]: n for n in names})
    glyphs = {".notdef": TTGlyphPen(None).glyph()}
    for name in names:
        glyphs[name] = glyph(outline(SVG_DIR / f"{name}.svg"))
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({n: (UPM, glyphs[n].xMin if n != ".notdef" else 0)
                               for n in order})
    fb.setupHorizontalHeader(ascent=UPM, descent=0)
    fb.setupNameTable({"familyName": FAMILY, "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=UPM, sTypoDescender=0, sTypoLineGap=0,
                usWinAscent=UPM, usWinDescent=0)
    fb.setupPost()
    FONT_OUT.parent.mkdir(parents=True, exist_ok=True)
    fb.save(FONT_OUT)


def dart_name(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "", name)


def write_dart(names: list[str], codepoints: dict[str, int]) -> None:
    lines = [
        "// GENERATED by tools/grocery_icons/build.py. Do not edit by hand:",
        "// change the SVGs in tools/grocery_icons/svg/ and run the script.",
        "",
        "import 'package:flutter/widgets.dart';",
        "",
        "/// Nest's own grocery icons, drawn in Lucide's style for groceries",
        "/// Lucide has no glyph for.",
        "abstract final class GroceryIcons {",
    ]
    for name in names:
        lines.append(
            f"  static const IconData {dart_name(name)} = "
            f"IconData(0x{codepoints[name]:x}, fontFamily: '{FAMILY}');"
        )
    lines += [
        "}",
        "",
        "/// The icons above by catalog `iconKey`.",
        "const groceryIconsByKey = <String, IconData>{",
    ]
    for name in names:
        lines.append(f"  '{name}': GroceryIcons.{dart_name(name)},")
    lines += ["};", ""]
    DART_OUT.write_text("\n".join(lines))


def write_preview(names: list[str], codepoints: dict[str, int]) -> None:
    BUILD.mkdir(exist_ok=True)
    shutil.copy(FONT_OUT, BUILD / "grocery.ttf")
    if LUCIDE_TTF.exists():
        shutil.copy(LUCIDE_TTF, BUILD / "lucide.ttf")
    lucide = {"apple": 0xE34E, "carrot": 0xE25A, "milk": 0xE399, "egg": 0xE25D,
              "fish": 0xE3A6, "beef": 0xE3A5, "cookie": 0xE26B, "soup": 0xE3AA}
    tiles = "".join(
        f"<div class=t><span class=l>&#x{cp:x};</span>{n}</div>"
        for n, cp in lucide.items()
    )
    rows = "".join(
        f"<div class=t>{(SVG_DIR / f'{n}.svg').read_text()}"
        f"<span class=f>&#x{codepoints[n]:x};</span>{n}</div>"
        for n in names
    )
    (BUILD / "preview.html").write_text(f"""<!doctype html><meta charset=utf-8>
<title>Grocery icons</title>
<style>
@font-face{{font-family:L;src:url(lucide.ttf)}}
@font-face{{font-family:G;src:url(grocery.ttf)}}
body{{font-family:sans-serif;margin:12px;background:#fff}}
.g{{display:flex;flex-wrap:wrap;gap:8px}}
.t{{width:120px;height:96px;background:#dfe9dc;color:#2f4a33;border-radius:14px;
display:flex;flex-wrap:wrap;align-items:center;justify-content:center;gap:4px 10px;
font-size:11px;align-content:center}}
.t svg{{width:30px;height:30px}}
.l,.f{{font-size:30px;line-height:1}}.l{{font-family:L}}.f{{font-family:G}}
.t>:last-child{{width:100%;text-align:center}}
</style>
<h3>Lucide (font)</h3><div class=g>{tiles}</div>
<h3>Nest: SVG (left) and font (right)</h3><div class=g>{rows}</div>
""")


def main() -> None:
    names = sorted(p.stem for p in SVG_DIR.glob("*.svg"))
    codepoints = load_codepoints(names)
    build_font(names, codepoints)
    write_dart(names, codepoints)
    write_preview(names, codepoints)
    print(f"{len(names)} icons -> {FONT_OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
